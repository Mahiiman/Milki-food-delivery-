export function translateText(value, language = 'om') {
  if (typeof value !== 'string' || language === 'om') return value
  return translations[language]?.[value.trim()] ?? value
}

export function Translate({ language, children }) {
  function translateNode(node) {
    if (typeof node === 'string') return translateText(node, language)
    if (Array.isArray(node)) return node.map(translateNode)
    if (!React.isValidElement(node)) return node

    const props = {}
    for (const [key, value] of Object.entries(node.props)) {
      if (key === 'children') {
        props.children = translateNode(value)
      } else if (
        typeof value === 'string' &&
        ['placeholder', 'title', 'aria-label'].includes(key)
      ) {
        props[key] = translateText(value, language)
      } else {
        props[key] = value
      }
    }
    return React.cloneElement(node, props)
  }

  return translateNode(children)
}
